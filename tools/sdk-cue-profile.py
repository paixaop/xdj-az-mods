"""Generate cue owner/lifecycle profiles from both identified stock images."""
import argparse
import importlib.util
from pathlib import Path
import struct
ROOT = Path(__file__).resolve().parents[1]
spec = importlib.util.spec_from_file_location('exit_profiles', ROOT/'tools/sdk-exit-profile.py')
x = importlib.util.module_from_spec(spec)
spec.loader.exec_module(x)
STORE = {
 '1.30': (0x80b548,0x811c90,0x811e98,0x1493668,0x811920,0x80b0f0,0x816e78,0x13e7e98,0x1492ac0,0x14939b0,0x80aac0,0x8121c8,0x1492ce0),
 '2.00': (0x850f30,0x8575e8,0x8577f0,0x154eba8,0x857278,0x850ad8,0x85c778,0x14a32d8,0x154e030,0x154eed0,0x8504a8,0x857b20,0x154e220),
}
PERSIST = {
 '1.30': (0x825ac8,0x8258d0,0x824e08,0x82b2d8,0x82ac18,0x825d48,0x2616d78,0x2616d00,0x2367d90,0x230f5c0,0x22fc600,0x23a5080,0x1735238,0x811c90,0x811e98,0x172e5d8,0x172e620,0x1734b38,0x1730710,0x1734f00,0x1734798,0x17303d8,0x80aee0,0x80b0f0),
 '2.00': (0x86b410,0x86b218,0x86a750,0x870c90,0x8705d0,0x86b690,0x2951208,0x2951190,0x24d5230,0x247ca60,0x2469aa0,0x2512520,0x1890808,0x8575e8,0x8577f0,0x1889c30,0x1889bd0,0x1890108,0x188bce0,0x18904d0,0x188fd68,0x188b9a8,0x8508c8,0x850ad8),
}
def secondary(image, primary_table, offset):
 typeinfo=struct.unpack('<Q',image.file_bytes(primary_table-8,8))[0]
 needle=struct.pack('<qQ',offset,typeinfo)
 tables=set()
 for base,file_offset,size,_,_ in image.loads:
  pos=file_offset
  while True:
   pos=image.data.find(needle,pos,file_offset+size)
   if pos<0:break
   address=base+pos-file_offset+16
   if address%8==0 and x.executable(image,struct.unpack('<Q',image.file_bytes(address,8))[0]):tables.add(address)
   pos+=1
 if len(tables)!=1:raise ValueError('missing/ambiguous cue manager secondary box')
 return tables.pop()
def generate(folder):
 catalog=x.addrgen.read_catalog(ROOT/'tools/ep147-addresses.json')
 images=x.addrgen.load_images(catalog,folder)
 lines=['/* Generated by tools/sdk-cue-profile.py. */','#include "../common/azcueprofile.h"','static const struct azcue_profile cue_profiles[2] = {']
 for version in ('1.30','2.00'):
  image=images[version]
  manager=x.primary(image,'N8cue_call14CueCallManagerE')
  # The completed derived constructor replaces the generic shared-box table.
  box=secondary(image,manager,-8)
  if box!={'1.30':0x26143a8,'2.00':0x294e838}[version]:raise ValueError('cue manager secondary box changed')
  owner=x.primary(image,'N4meow22SharedTaskDrivenThreadINS_25TaskDrivenThreadWithTimerEE14InternalThreadE')
  task={'1.30':0x2614930,'2.00':0x294edc0}[version]
  execute=x.method(image,task,2)
  complete=x.method(image,task,0)
  expected={'1.30':(0x2614318,0x819fd0,0x81a730),'2.00':(0x294e7a8,0x85f8d0,0x860030)}[version]
  if (manager,execute,complete)!=expected:raise ValueError('cue owner table changed')
  # Task execute is a three-instruction tail thunk: validate bytes, do not inline patch it.
  actor=(manager,box,owner,task,x.method(image,manager,2),x.method(image,box,6),execute,complete)
  x.entry(image,actor[5])  # post is intercepted inline; reject unsafe relocation
  entries=[x.entry(image,{'1.30':0x81ec88,'2.00':0x864588}[version]),x.entry(image,x.method(image,manager,0)),x.entry(image,x.method(image,manager,1))]
  stores=[x.entry(image,a,require_inline=False) for a in STORE[version]]
  lines+=['    {/* EP147 '+version+' */','     {'+', '.join(hex(a) for a in actor)+'},']
  lines+=['     {'+hex(a)+', '+x.byte_array(p)+'},' for a,p in entries]
  lines+=['     {']+['      {'+hex(a)+', '+x.byte_array(p)+'},' for a,p in stores]+['     },']
  persist=PERSIST[version]
  lines+=['     {'+', '.join(hex(a) for a in persist)+'},','     {']
  lines+=['      {'+hex(a)+', '+x.byte_array(p)+'},' for a,p in (x.entry(image,a) for a in (*persist[2:6],persist[12],persist[19]))]+['     },','     {']
  lines+=['      {'+hex(a)+', '+x.byte_array(p)+'},' for a,p in (x.entry(image,a,require_inline=False) for a in actor[4:])]+['     },','     {']
  lines+=['      {'+hex(a)+', '+x.byte_array(p)+'},' for a,p in (x.entry(image,a,require_inline=False) for a in persist[12:])]+['     }},']
 return '\n'.join(lines+['};',''])
if __name__=='__main__':
 p=argparse.ArgumentParser();p.add_argument('--firmware',type=Path,required=True);p.add_argument('--check',action='store_true');a=p.parse_args()
 path=ROOT/'src/azstem/sdk_cue_profiles.h';text=generate(a.firmware)
 if a.check:
  if path.read_text()!=text:raise SystemExit('cue profiles differ')
 else:path.write_text(text)
 print('Cue profiles: both stock images verified')
